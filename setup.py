#!/usr/bin/env python3
"""Generate the go2rtc config for a Hikvision NVR from .env.

Reads .env, asks the NVR which IP channels exist (ISAPI, digest auth) and
writes into OUT_DIR (default ./build):
  go2rtc.yaml  - stream definitions; credentials referenced as ${VARS}
  go2rtc.env   - URL-encoded credentials for the container (mode 600)
  streams.json - channel and stream names for the web player (no secrets)
With NVR_ENCRYPTED=1 (the default) the streams go through hikdecrypt.py,
which undoes Hikvision's stream encryption. Recordings always do (pb1..pb16).

Usually run for you by deploy/install.sh, which installs them in /etc/go2rtc.

usage: setup.py [--env PATH] [--out OUT_DIR]
"""
import argparse
import json
import os
import ssl
import sys
import urllib.parse
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PB_SLOTS = 16  # must match PB_SLOTS in localservice.py


def load_env(path):
    env = {}
    if not path.exists():
        sys.exit(f"{path} not found - copy .env.example to .env and fill it in.")
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        v = v.strip()
        if len(v) >= 2 and v[0] == v[-1] and v[0] in "'\"":
            v = v[1:-1]
        env[k.strip()] = v
    return env


def detect_channels(host, user, password):
    """Return [(id, name)] of IP channels configured on the NVR, or None."""
    url = f"https://{host}/ISAPI/ContentMgmt/InputProxy/channels"
    ctx = ssl.create_default_context()
    ctx.check_hostname = False
    ctx.verify_mode = ssl.CERT_NONE  # NVR uses a self-signed certificate
    pw = urllib.request.HTTPPasswordMgrWithDefaultRealm()
    pw.add_password(None, f"https://{host}/", user, password)
    opener = urllib.request.build_opener(
        urllib.request.HTTPSHandler(context=ctx),
        urllib.request.HTTPDigestAuthHandler(pw),
    )
    try:
        with opener.open(url, timeout=10) as r:
            root = ET.fromstring(r.read())
    except Exception as e:  # noqa: BLE001 - report and fall back
        print(f"  channel auto-detection failed: {e}", file=sys.stderr)
        return None
    chans = []
    for el in root.iter():
        if el.tag.endswith("InputProxyChannel"):
            cid = name = None
            for c in el:
                if c.tag.endswith("}id") or c.tag == "id":
                    cid = int(c.text)
                elif c.tag.endswith("}name") or c.tag == "name":
                    name = (c.text or "").strip()
            if cid:
                chans.append((cid, name or f"Camera {cid:02d}"))
    return sorted(chans) or None


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--env", type=Path, default=ROOT / ".env")
    ap.add_argument("--out", type=Path, default=ROOT / "build")
    args = ap.parse_args()
    env = load_env(args.env)
    for k in ("NVR_HOST", "NVR_USER", "NVR_PASS"):
        if not env.get(k):
            sys.exit(f"{k} is missing from .env")
    host, user, password = env["NVR_HOST"], env["NVR_USER"], env["NVR_PASS"]
    transcode = env.get("NVR_TRANSCODE", "0") == "1"
    encrypted = env.get("NVR_ENCRYPTED", "1") == "1"

    print(f"Asking {host} for its channels...")
    chans = detect_channels(host, user, password)
    if chans is None:
        n = int(env.get("NVR_CHANNELS", "8"))
        print(f"  using NVR_CHANNELS={n} from .env")
        chans = [(i, f"Camera {i:02d}") for i in range(1, n + 1)]
    else:
        for cid, name in chans:
            print(f"  channel {cid}: {name}")

    base = "rtsp://${NVR_USER_URL}:${NVR_PASS_URL}@${NVR_HOST}:554/Streaming/Channels"
    lines = [
        "# Generated by setup.py - edit .env and re-run instead of editing this.",
        "api:",
        '  listen: "127.0.0.1:1984"',
        "rtsp:",
        '  listen: "127.0.0.1:18554"',
        "webrtc:",
        '  listen: "127.0.0.1:8555"',
        "  candidates:",
        '    - "127.0.0.1:8555"',
        "streams:",
    ]
    for cid, name in chans:
        lines.append(f"  # {name}")
        for suffix, n in (("main", f"{cid}01"), ("sub", f"{cid}02")):
            if encrypted:  # decrypted by hikdecrypt.py, which publishes to go2rtc
                src = f"exec:python3 -I /config/hikdecrypt.py {n} {{output}}"
            else:
                src = f"{base}/{n}"
            lines.append(f"  ch{cid}_{suffix}: {src}")
        if transcode:
            lines.append(f"  ch{cid}_main_h264: ffmpeg:ch{cid}_main#video=h264")
    # Recordings: playback slots, assigned by localservice.py, which tells
    # hikdecrypt.py what to play. Nothing runs until someone plays one.
    lines.append("  # Playback (Playback page, via localservice.py)")
    for i in range(1, PB_SLOTS + 1):
        lines.append(f"  pb{i}: exec:python3 -I /config/hikdecrypt.py --slot {i} {{output}}")
    out = args.out
    out.mkdir(mode=0o700, parents=True, exist_ok=True)
    q = lambda s: urllib.parse.quote(s, safe="")  # noqa: E731
    files = {
        "go2rtc.yaml": "\n".join(lines) + "\n",
        "go2rtc.env": f"NVR_HOST={host}\nNVR_USER_URL={q(user)}\nNVR_PASS_URL={q(password)}\n"
                      + (f"NVR_KEY_URL={q(env['NVR_KEY'])}\n" if env.get("NVR_KEY") else ""),
    }
    for name, text in files.items():
        fd = os.open(out / name, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "w") as f:
            f.write(text)
        os.chmod(out / name, 0o600)
    streams = [{"id": cid, "name": name,
                "streams": ["main", "sub"] + (["main_h264"] if transcode else [])}
               for cid, name in chans]
    (out / "streams.json").write_text(json.dumps({"channels": streams}, indent=1) + "\n")
    os.chmod(out / "streams.json", 0o644)
    print(f"Wrote {out}/go2rtc.yaml ({len(chans)} channels), {out}/go2rtc.env and {out}/streams.json")


if __name__ == "__main__":
    main()
